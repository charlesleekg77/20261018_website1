import { motion, useScroll, useTransform } from 'framer-motion';
import { useRef } from 'react';

import { MARQUEE_PHRASES } from '../data/manifesto';
import { usePrefersReducedMotion } from '../hooks/useMediaQuery';
import GrainCanvas from './GrainCanvas';
import Marquee from './Marquee';
import { MaskLines } from './Reveal';
import StampEffect from './StampEffect';

const FACTS = [
  { key: 'Founded', value: '2019' },
  { key: 'Projects shipped', value: '140+' },
  { key: 'Generated by AI', value: '0' },
  { key: 'Humans on staff', value: '11' },
];

export default function Hero() {
  const sectionRef = useRef<HTMLElement>(null);
  const reducedMotion = usePrefersReducedMotion();
  const { scrollYProgress } = useScroll({
    target: sectionRef,
    offset: ['start start', 'end start'],
  });
  const y = useTransform(scrollYProgress, [0, 1], ['0%', '18%']);
  const opacity = useTransform(scrollYProgress, [0, 0.85], [1, 0.15]);

  return (
    <StampEffect
      className="relative isolate overflow-hidden border-b border-offwhite/15 bg-charcoal"
      accent="acid"
      sealLabel="APPROVED BY HUMANS"
      sealSub="NO AI"
    >
      <section
        ref={sectionRef}
        id="hero"
        data-cursor-stamp="STAMP IT"
        className="relative flex min-h-[100svh] flex-col justify-between pt-28 pb-0 sm:pt-32"
        aria-labelledby="hero-heading"
      >
        <div aria-hidden="true" className="absolute inset-0 -z-10">
          <GrainCanvas className="opacity-95" intensity={1} />
          <div className="scanlines absolute inset-0 opacity-25 mix-blend-multiply" />
          <div className="absolute inset-0 bg-gradient-to-b from-charcoal/40 via-transparent to-charcoal" />
        </div>

        <motion.div style={reducedMotion ? undefined : { y, opacity }} className="shell relative z-10">
          <div className="flex flex-wrap items-center gap-x-6 gap-y-3 border-b border-offwhite/15 pb-5">
            <span className="label-type text-signal">Est. 2019 &mdash; independent human studio</span>
            <span className="label-type text-offwhite/45">Rotterdam / Leeds</span>
            <span className="label-type ml-auto hidden items-center gap-2 text-acid sm:flex">
              <span className="h-1.5 w-1.5 animate-blink bg-acid" />
              Click anywhere to stamp it
            </span>
          </div>

          <h1 id="hero-heading" className="hero-type mt-8 max-w-[22ch] text-offwhite sm:mt-10">
            <MaskLines
              lines={[
                <span key="l1" className="block">
                  Death to <span className="text-signal">robots</span>.
                </span>,
                <span key="l2" className="block">
                  Long live <span className="text-acid">human</span> creativity.
                </span>,
              ]}
              delay={0.1}
            />
          </h1>

          <div className="mt-10 grid gap-8 border-t border-offwhite/15 pt-8 lg:grid-cols-[1.15fr_1fr]">
            <p className="max-w-2xl font-serif text-xl leading-snug text-offwhite/85 sm:text-2xl md:text-3xl">
              A revolt against generic AI sludge. We build handcrafted digital experiences, human
              storytelling, and soul-infused design.
            </p>

            <div className="flex flex-col gap-5">
              <p className="max-w-md font-mono text-sm leading-relaxed text-offwhite/55">
                No prompt was pasted into a box and shipped as if it were a decision. Every line of
                code, every sentence, every pixel on this page was made by a person with a name.
              </p>

              <div className="flex flex-wrap gap-3">
                <a
                  href="#manifesto"
                  data-cursor-label="READ"
                  className="label-type border border-offwhite/25 px-5 py-3 text-offwhite transition-colors hover:border-acid hover:bg-acid hover:text-ink"
                >
                  Read the manifesto
                </a>
                <a
                  href="#works"
                  data-cursor-label="SEE"
                  className="label-type border border-signal bg-signal px-5 py-3 text-ink transition-colors hover:border-acid hover:bg-acid"
                >
                  See human works
                </a>
              </div>
            </div>
          </div>
        </motion.div>

        <div className="relative z-10 mt-12">
          <dl className="shell grid grid-cols-2 border-t border-offwhite/15 lg:grid-cols-4">
            {FACTS.map((fact, index) => (
              <div
                key={fact.key}
                className={`flex flex-col gap-1 border-offwhite/15 py-5 ${
                  index % 2 === 1 ? 'border-l pl-5' : 'pr-5'
                } ${index > 1 ? 'border-t lg:border-t-0' : ''} ${
                  index > 0 ? 'lg:border-l lg:pl-5' : ''
                }`}
              >
                <dt className="label-type text-offwhite/40">{fact.key}</dt>
                <dd
                  className={`font-display text-3xl font-extrabold tracking-tight sm:text-4xl ${
                    fact.value === '0' ? 'text-acid' : 'text-offwhite'
                  }`}
                >
                  {fact.value}
                </dd>
              </div>
            ))}
          </dl>

          <Marquee
            items={MARQUEE_PHRASES}
            durationSeconds={26}
            className="border-y border-offwhite/15 bg-ink py-4"
            itemClassName="font-display text-2xl font-extrabold uppercase tracking-tight text-offwhite sm:text-5xl"
          />
        </div>
      </section>
    </StampEffect>
  );
}
